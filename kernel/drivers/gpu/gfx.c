#define FONT_FIRST 0x20
#define FONT_LAST  0x7E

void gfx_draw_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color)
{
    for (uint32_t row = y; row < y + h; row++)
        for (uint32_t col = x; col < x + w; col++)
            fb_put_pixel(col, row, color);
}

void gfx_draw_line(int x0, int y0, int x1, int y1, uint32_t color)
{
    /* Bresenham's line algorithm */
    int dx =  (x1 > x0) ? (x1 - x0) : (x0 - x1);
    int dy = -((y1 > y0) ? (y1 - y0) : (y0 - y1));
    int sx = x0 < x1 ? 1 : -1;
    int sy = y0 < y1 ? 1 : -1;
    int err = dx + dy;

    while (true) {
        fb_put_pixel((uint32_t)x0, (uint32_t)y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

void gfx_draw_char(uint32_t x, uint32_t y, char c, uint32_t fg, uint32_t bg)
{
    if (!g_fb.valid) return;
    if (c < FONT_FIRST || c > FONT_LAST) c = '?';
    const uint8_t *glyph = font8x8[(uint8_t)(c - FONT_FIRST)];
    for (int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            fb_put_pixel(x + (uint32_t)col, y + (uint32_t)row,
                         (bits & (0x80 >> col)) ? fg : bg);
        }
    }
}

void gfx_draw_string(uint32_t x, uint32_t y, const char *s, uint32_t fg, uint32_t bg)
{
    uint32_t cx = x;
    while (*s) {
        if (*s == '\n') { cx = x; y += 9; }
        else            { gfx_draw_char(cx, y, *s, fg, bg); cx += 9; }
        s++;
    }
}
